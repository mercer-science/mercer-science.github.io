def scope_css(css, scope):
    """Rewrite a print stylesheet so every rule applies only inside `scope`.

    The rules come straight from make_resumes.py and make_cv.py, so each page
    and its PDF share one stylesheet and cannot drift apart.
    """
    out = []
    for rule in css.split("}"):
        if "{" not in rule:
            continue
        sel, body = rule.split("{", 1)
        sel = sel.strip()
        if sel.startswith("@"):
            continue
        parts = []
        for one in sel.split(","):
            one = one.strip()
            if not one:
                continue
            parts.append(scope if one == "body" else "%s %s" % (scope, one))
        out.append("%s {%s}" % (", ".join(parts), body))
    return out


def sheet_css():
    """The paper sheets: the resume and the CV, each rendered as the PDF prints it."""
    out = [
        "/* Generated by tools/build.py from tools/make_resumes.py and tools/make_cv.py.",
        "   Do not edit by hand. */",
        # 100vw counts the scrollbar, so the sheet keeps 48px of room rather
        # than 32px and never pushes the page sideways.
        ".sheet-wrap { position: relative; width: min(8.5in, calc(100vw - 48px));",
        "  margin: 0.4rem auto 0; overflow: hidden; }",
        ".sheet { width: 8.5in; background: #fff; color: #1b1b1f;",
        "  border: 1px solid var(--line); border-radius: 4px;",
        "  transform-origin: top left; box-shadow: 0 2px 14px rgba(0,0,0,0.13); }",
        ".sheet-resume { min-height: 11in; padding: 0.45in 0.5in; }",
        ".sheet-cv { padding: 0.6in 0.65in; }",
        ".sheet * { color: inherit; }",
        # The download button sits in the sheet's top-left corner. It lives on
        # the wrapper rather than inside the sheet, so it keeps its own size
        # when the sheet is scaled down on a narrow screen.
        ".sheet-wrap .downloads { position: absolute; top: 10px; left: 10px;",
        "  margin: 0; z-index: 2; }",
        ".sheet-wrap .button-icon { width: 2rem; height: 2rem;",
        "  box-shadow: 0 1px 6px rgba(0,0,0,0.25); }",
    ]
    out += scope_css(make_resumes.CSS, ".sheet-resume")
    out += scope_css(make_cv.CSS, ".sheet-cv")
    return "\n".join(out) + "\n"


# An arrow into a tray: the usual download mark. The label is real text for
# screen readers and for the tooltip, so the button is not an unlabeled icon.
DOWNLOAD_ICON = (
    '<svg viewBox="0 0 24 24" width="20" height="20" fill="none" stroke="currentColor" '
    'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" '
    'focusable="false"><path d="M12 3v12"></path><path d="M7 11l5 5 5-5"></path>'
    '<path d="M4 19h16"></path></svg>'
)


def download_button(href, label):
    return ('<p class="downloads"><a class="button button-icon" href="../%s" download '
            'title="%s" aria-label="%s">%s<span class="sr-only">%s</span></a></p>'
            % (href, html.escape(label, quote=True), html.escape(label, quote=True),
               DOWNLOAD_ICON, html.escape(label)))


def render_sheet(kind, body, pdf_href, label):
    """A paper sheet with its download button pinned to the top-left corner."""
    return ('<div class="sheet-wrap">%s<div class="sheet sheet-%s">%s</div></div>'
            % (download_button(pdf_href, label), kind, body))


def render_images(images):
    if not images:
        return ""
    figs = []
    for img in images:
        src = img.get("src", "")
        alt = html.escape(img.get("alt", ""), quote=True)
        caption = img.get("caption", "")
        cap = '<figcaption>%s</figcaption>' % inline(caption) if caption else ""
        figs.append(
            '<figure class="shot">\n'
            '<a href="../%s"><img src="../%s" alt="%s" loading="lazy"></a>\n%s\n</figure>'
            % (src, src, alt, cap)
        )
    cls = "figures" + (" figures-pair" if len(figs) == 2 else "")
    return '<div class="%s">\n%s\n</div>' % (cls, "\n".join(figs))


def render_block(meta, tab_title="", role_id=""):
    title = meta.get("title", "")
    # A block whose title repeats the tab's own title shows it once, not twice.
    repeat_title = title.strip().lower() == tab_title.strip().lower()
    status = str(meta.get("status") or "").strip()
    dates = str(meta.get("dates") or "").strip()
    # The resume and the CV are documents. They carry their own white page, so
    # the card the other blocks sit on would only box a box.
    is_sheet = bool(meta.get("resume_pdf") or meta.get("cv_pdf"))
    pieces = []
    pieces.append('<article class="block%s" id="%s">'
                  % (" block-bare" if is_sheet else "",
                     slugify(meta["_name"].split("/")[-1])))
    pieces.append('<header class="block-head">')
    if not repeat_title and not is_sheet:
        pieces.append("<h2>%s</h2>" % inline(title))
    meta_bits = []
    if dates:
        meta_bits.append('<span class="dates">%s</span>' % inline(dates))
    if status:
        ongoing = " ongoing" if status.lower().startswith("ongoing") else ""
        meta_bits.append('<span class="status%s">%s</span>' % (ongoing, inline(status)))
    if meta_bits:
        pieces.append('<p class="block-meta">%s</p>' % " ".join(meta_bits))
    pieces.append("</header>")

    # The Resume and CV tabs show the document itself, so the headline and any
    # prose in the markdown would only repeat what the sheet already says.
    if meta.get("headline") and not is_sheet:
        pieces.append('<p class="headline">%s</p>' % inline(meta["headline"]))
    if not is_sheet:
        pieces.append(render_markdown(meta["_body"]))

    if meta.get("resume_pdf"):
        pieces.append(render_sheet("resume", make_resumes.resume_body(role_id),
                                   meta["resume_pdf"], "Download Resume (PDF)"))
    if meta.get("cv_pdf"):
        pieces.append(render_sheet("cv", make_cv.cv_body(),
                                   meta["cv_pdf"], "Download CV (PDF)"))

    pieces.append(render_images(meta.get("images") or []))
    pieces.append("</article>")
    return "\n".join(p for p in pieces if p)


def role_switcher(current, roles):
    chips = []
    for rid in ROLE_ORDER:
        if rid not in roles:
            continue
        label = roles[rid]["label"]
        if rid == current:
            chips.append('<span class="chip chip-on" aria-current="page">%s</span>' % html.escape(label))
        else:
            chips.append('<a class="chip" href="../%s/">%s</a>' % (rid, html.escape(label)))
    return (
        '<nav class="roles" aria-label="Application">\n'
        '<span class="roles-label">Application:</span>\n%s\n</nav>' % "\n".join(chips)
    )


def tab_bar(tabs):
    buttons = []
    for i, tab in enumerate(tabs):
        buttons.append(
            '<a class="tab%s" href="#%s" data-tab="%s" role="tab" aria-selected="%s">%s</a>'
            % (" tab-on" if i == 0 else "", tab["id"], tab["id"],
               "true" if i == 0 else "false", html.escape(tab["title"]))
        )
    return '<nav class="tabs" role="tablist" aria-label="Sections">\n%s\n</nav>' % "\n".join(buttons)


