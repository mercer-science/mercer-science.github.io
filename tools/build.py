def resume_sheet_css():
    """Scope the resume's own print CSS under .sheet so it cannot touch the site.

    The rules come straight from make_resumes.py, so the page and the PDF share
    one stylesheet and stay identical.
    """
    out = [
        "/* Generated by tools/build.py from tools/make_resumes.py. Do not edit by hand. */",
        # 100vw counts the scrollbar, so the sheet keeps 48px of room rather
        # than 32px and never pushes the page sideways.
        ".resume-wrap { width: min(8.5in, calc(100vw - 48px));",
        "  margin: 1.1rem 0 0 calc(50% - min(8.5in, 100vw - 48px) / 2);",
        "  overflow: hidden; }",
        ".sheet { width: 8.5in; min-height: 11in; background: #fff; color: #1b1b1f;",
        "  padding: 0.45in 0.5in; border: 1px solid var(--line); border-radius: 6px;",
        "  transform-origin: top left; box-shadow: 0 1px 10px rgba(0,0,0,0.10); }",
        ".sheet * { color: inherit; }",
    ]
    for rule in make_resumes.CSS.split("}"):
        if "{" not in rule:
            continue
        sel, body = rule.split("{", 1)
        sel = sel.strip()
        if sel.startswith("@"):
            continue
        parts = []
        for one in sel.split(","):
            one = one.strip()
            if not one:
                continue
            parts.append(".sheet" if one == "body" else ".sheet %s" % one)
        out.append("%s {%s}" % (", ".join(parts), body))
    return "\n".join(out) + "\n"


def render_resume(role_id):
    return '<div class="resume-wrap"><div class="sheet">%s</div></div>' % \
        make_resumes.resume_body(role_id)


def render_images(images):
    if not images:
        return ""
    figs = []
    for img in images:
        src = img.get("src", "")
        alt = html.escape(img.get("alt", ""), quote=True)
        caption = img.get("caption", "")
        cap = '<figcaption>%s</figcaption>' % inline(caption) if caption else ""
        figs.append(
            '<figure class="shot">\n'
            '<a href="../%s"><img src="../%s" alt="%s" loading="lazy"></a>\n%s\n</figure>'
            % (src, src, alt, cap)
        )
    cls = "figures" + (" figures-pair" if len(figs) == 2 else "")
    return '<div class="%s">\n%s\n</div>' % (cls, "\n".join(figs))


def render_block(meta, tab_title="", role_id=""):
    title = meta.get("title", "")
    # A block whose title repeats the tab's own title shows it once, not twice.
    repeat_title = title.strip().lower() == tab_title.strip().lower()
    status = str(meta.get("status") or "").strip()
    dates = str(meta.get("dates") or "").strip()
    pieces = []
    pieces.append('<article class="block" id="%s">' % slugify(meta["_name"].split("/")[-1]))
    pieces.append('<header class="block-head">')
    if not repeat_title:
        pieces.append("<h2>%s</h2>" % inline(title))
    meta_bits = []
    if dates:
        meta_bits.append('<span class="dates">%s</span>' % inline(dates))
    if status:
        ongoing = " ongoing" if status.lower().startswith("ongoing") else ""
        meta_bits.append('<span class="status%s">%s</span>' % (ongoing, inline(status)))
    if meta_bits:
        pieces.append('<p class="block-meta">%s</p>' % " ".join(meta_bits))
    pieces.append("</header>")

    is_resume = bool(meta.get("resume_pdf"))

    # The Resume tab shows the resume itself, so the headline and any prose in
    # the markdown would only repeat what the sheet already says.
    if meta.get("headline") and not is_resume:
        pieces.append('<p class="headline">%s</p>' % inline(meta["headline"]))
    if not is_resume:
        pieces.append(render_markdown(meta["_body"]))

    if is_resume:
        pieces.append(
            '<p class="downloads"><a class="button" href="../%s" download>Download Resume (PDF)</a></p>'
            % meta["resume_pdf"]
        )
        pieces.append(render_resume(role_id))
    if meta.get("cv_pdf"):
        pieces.append(
            '<p class="downloads"><a class="button" href="../%s" download>Download CV (PDF)</a></p>'
            % meta["cv_pdf"]
        )

    pieces.append(render_images(meta.get("images") or []))
    pieces.append("</article>")
    return "\n".join(p for p in pieces if p)


def role_switcher(current, roles):
    chips = []
    for rid in ROLE_ORDER:
        if rid not in roles:
            continue
        label = roles[rid]["label"]
        if rid == current:
            chips.append('<span class="chip chip-on" aria-current="page">%s</span>' % html.escape(label))
        else:
            chips.append('<a class="chip" href="../%s/">%s</a>' % (rid, html.escape(label)))
    return (
        '<nav class="roles" aria-label="Application">\n'
        '<span class="roles-label">Application:</span>\n%s\n</nav>' % "\n".join(chips)
    )


def tab_bar(tabs):
    buttons = []
    for i, tab in enumerate(tabs):
        buttons.append(
            '<a class="tab%s" href="#%s" data-tab="%s" role="tab" aria-selected="%s">%s</a>'
            % (" tab-on" if i == 0 else "", tab["id"], tab["id"],
               "true" if i == 0 else "false", html.escape(tab["title"]))
        )
    return '<nav class="tabs" role="tablist" aria-label="Sections">\n%s\n</nav>' % "\n".join(buttons)


